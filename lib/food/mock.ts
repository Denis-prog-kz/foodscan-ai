/**
 * Детерминированно выбирает мок-блюдо на основе размера изображения,
 * чтобы одинаковое фото давало стабильный результат, но разные фото — разные.
 */
export function getMockAnalysis(seed = Math.random() * 1000): FoodAnalysis {
  const index = Math.floor(Math.abs(seed)) % MOCK_MEALS.length
  const base = MOCK_MEALS[index]
  // небольшая вариативность калорий для реалистичности
  const jitter = 1 + ((Math.abs(seed) % 7) - 3) / 100
  return {
    ...base,
    calories: Math.round(base.calories * jitter),
    protein: Math.round(base.protein * jitter),
    fat: Math.round(base.fat * jitter),
    carbs: Math.round(base.carbs * jitter),
  }
}
